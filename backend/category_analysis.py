"""Read-only category proposal audit; writes nothing, including no SQLite cache.

From repository root:
    .venv/bin/python backend/category_analysis.py
    .venv/bin/python -m backend.category_analysis --compact

Only pandas and the standard library are needed. The adjacent mapping CSV is
the editable proposal and is never regenerated by this script. Full output is
Markdown on stdout; --compact omits long detail/case/year tables. No report file
is created unless the caller explicitly redirects stdout.

Mapping contract: normalize whitespace exactly like explorer_data.text, then
match service_name exactly (empty means missing). An `in` rule matches one of
the pipe-separated, exact normalized detail_values. It takes priority over the
single `fallback` row for that service. `any` is unconditional and cannot coexist
with conditional rows. Case is preserved; no fuzzy or keyword inference occurs.
Unknown future services fail validation; unknown future details use the explicit
fallback and are printed for review. Each observed detail condition is validated
against the full source, including historical records absent from the Explorer.
"""

import argparse
import csv
import hashlib
from pathlib import Path
import sys

import pandas as pd

# Import only pure parsing helpers. Never call ensure_cache/build_cache/connect.
sys.dont_write_bytecode = True
if __package__:
    from . import explorer_data as explorer
else:
    import explorer_data as explorer

HERE = Path(__file__).resolve().parent
SOURCE = HERE / 'Raw Data/Get it done/get_it_done_requests_CD1_datasd.csv'
MAPPING = HERE / 'category_mapping.csv'
MISSING = '（缺失）'


def normalized(series):
    return series.map(lambda value: explorer.text(value) or '')


def table(title, frame):
    """Print portable Markdown without an optional tabulate dependency."""
    def cell(value):
        return str(value).replace('|', '&#124;').replace('\n', ' ')

    print('\n## ' + title + '\n')
    print('| ' + ' | '.join(map(cell, frame.columns)) + ' |')
    print('| ' + ' | '.join('---' for _ in frame.columns) + ' |')
    for row in frame.itertuples(index=False, name=None):
        print('| ' + ' | '.join(map(cell, row)) + ' |')


def display(frame):
    return frame.replace('', MISSING).fillna(MISSING)


def counts(frame, columns, label):
    out = frame.groupby(columns, dropna=False).size().rename('count').reset_index()
    out = out.sort_values(['count', *columns], ascending=[False] + [True] * len(columns))
    out[label + '_pct'] = (out['count'] * 100 / len(frame)).round(4) if len(frame) else 0.0
    return out


def validate_mapping(mapping, raw):
    required = {'service_name', 'main_category', 'sub_category', 'detail_match', 'detail_values', 'notes'}
    if not required.issubset(mapping.columns):
        raise ValueError('Mapping missing columns: ' + str(required - set(mapping.columns)))
    for col in ('service_name', 'main_category', 'sub_category'):
        if not mapping[col].equals(normalized(mapping[col])):
            raise ValueError(f'Mapping has non-normalized whitespace in {col}')
    if (mapping[['main_category', 'sub_category']] == '').any().any():
        raise ValueError('Empty destination category')
    if not mapping.detail_match.isin(['in', 'any', 'fallback']).all():
        raise ValueError('Unsupported detail_match')
    if not 5 <= mapping.main_category.nunique() <= 8:
        raise ValueError('Expected 5–8 main categories')
    observed, defined = set(raw['_service']), set(mapping.service_name)
    if observed != defined:
        raise ValueError(f'Service coverage mismatch: unmapped={observed-defined}; invented={defined-observed}')
    for service, rules in mapping.groupby('service_name', sort=False):
        defaults = rules[rules.detail_match != 'in']
        conditions = rules[rules.detail_match == 'in']
        if len(defaults) != 1 or (len(conditions) and defaults.iloc[0].detail_match != 'fallback'):
            raise ValueError(f'Exactly one compatible default required for {service!r}')
        if defaults.detail_values.ne('').any():
            raise ValueError('Default rule cannot specify detail_values')
        seen = set()
        actual = set(raw.loc[raw['_service'] == service, '_detail'])
        for rule in conditions.itertuples():
            values = rule.detail_values.split('|')
            if '' in values or any(value != (explorer.text(value) or '') for value in values):
                raise ValueError(f'Invalid detail condition for {service!r}')
            if len(set(values)) != len(values) or seen.intersection(values):
                raise ValueError(f'Overlapping detail rules for {service!r}')
            if not set(values).issubset(actual):
                raise ValueError(f'Invented detail for {service!r}: {set(values)-actual}')
            seen.update(values)


def classify(frame, mapping):
    defaults = mapping[mapping.detail_match != 'in'].set_index('service_name')
    out = frame.copy()
    for destination in ('main_category', 'sub_category'):
        out[destination] = out['_service'].map(defaults[destination])
    for rule in mapping[mapping.detail_match == 'in'].itertuples():
        mask = out['_service'].eq(rule.service_name) & out['_detail'].isin(rule.detail_values.split('|'))
        out.loc[mask, ['main_category', 'sub_category']] = [rule.main_category, rule.sub_category]
    if out[['main_category', 'sub_category']].isna().any().any():
        raise ValueError('Unmapped record')
    return out


def scope_and_checks(raw):
    """Keep last normalized ID FIRST, then scope, matching cache delete semantics.

    Filtering before deduplication would wrongly retain an earlier in-scope row
    when the final occurrence moved outside District 1 or 2026.
    """
    ids = normalized(raw.service_request_id)
    dates = raw.date_requested.map(explorer.source_date)
    requested_year = dates.map(lambda date: (date or '')[:4])
    valid_id = ids.ne('')
    valid_date = dates.notna()
    district = raw.council_district.str.strip().eq('1')
    year = requested_year.eq('2026')
    last = ~ids.duplicated(keep='last')
    mask = last & valid_id & valid_date & district & year
    # Independently replay QHY's pure normalize() on every row, in source order.
    # This touches neither the existing cache nor any temporary SQLite database.
    replay = {}
    for row in raw[list(explorer.REQUIRED)].to_dict('records'):
        record = explorer.normalize(row)
        key = explorer.text(row['service_request_id'])
        if record is None:
            replay.pop(key, None)
        else:
            replay[key] = record
    scoped = raw.loc[mask].copy()
    if set(normalized(scoped.service_request_id)) != set(replay):
        raise ValueError('Pandas scope differs from QHY normalize replay')
    # Check normalized category and date too, rather than only total count.
    for row in scoped.itertuples():
        record = replay[explorer.text(row.service_request_id)]
        if record[1] != explorer.source_date(row.date_requested) or record[2] != explorer.text(row.service_name):
            raise ValueError('Projection field mismatch')
    stats = {
        'raw_rows': len(raw), 'columns': len(raw.columns),
        'exact_duplicate_rows_excess': int(raw.duplicated().sum()),
        'duplicate_normalized_id_rows_excess': int(ids[valid_id].duplicated().sum()),
        'rows_in_repeated_id_groups': int((ids.duplicated(False) & valid_id).sum()),
        'missing_ids': int((~valid_id).sum()), 'invalid_dates': int((~valid_date).sum()),
        'not_district_1_rows': int((~district).sum()),
        'not_2026_or_invalid_date_rows': int((~year).sum()),
        'last_id_rows': int(last.sum()), 'explorer_rows': len(scoped),
        'explorer_unlocated': sum(row[6] is None for row in replay.values()),
        'explorer_linked': sum(row[10] is not None for row in replay.values()),
        'explorer_first_date': min((row[1] for row in replay.values()), default=''),
        'explorer_last_date': max((row[1] for row in replay.values()), default=''),
        'scope_matches_qhy_normalize_replay': True,
    }
    return scoped, stats


def category_frequency(raw, scoped):
    a = counts(raw, ['_service'], 'raw').rename(columns={'count': 'raw_count'})
    b = counts(scoped, ['_service'], 'explorer').rename(columns={'count': 'explorer_count'})
    out = a.merge(b, how='left', on='_service').fillna(0).rename(columns={'_service': 'service_name'})
    out['explorer_count'] = out.explorer_count.astype(int)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compact', action='store_true', help='Omit long pair/case/year tables')
    args = parser.parse_args()
    # String-preserving read prevents IDs/ZIPs becoming floats or text NA tokens
    # becoming null. Inferred pandas dtypes are separately reported, not imposed.
    before = SOURCE.stat()
    with SOURCE.open('rb') as stream:
        digest_before = hashlib.file_digest(stream, 'sha256').hexdigest()
    with SOURCE.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.reader(stream)
        headers = next(reader)
        if len(headers) != len(set(headers)):
            raise ValueError('Duplicate source column name')
        for number, row in enumerate(reader, start=2):
            if len(row) != len(headers):
                raise ValueError(f'Malformed CSV logical record {number}')
    inferred = pd.read_csv(SOURCE, low_memory=False)
    raw = pd.read_csv(SOURCE, dtype=str, keep_default_na=False, encoding='utf-8-sig')
    required = explorer.REQUIRED | {'service_name_detail', 'case_record_type'}
    if not required.issubset(raw.columns):
        raise ValueError('Source missing fields: ' + str(required - set(raw.columns)))
    scoped, stats = scope_and_checks(raw)
    schema = pd.DataFrame({
        'field': raw.columns, 'pandas_inferred_dtype': inferred.dtypes.astype(str).to_numpy(),
        'pandas_default_na': inferred.isna().sum().to_numpy(),
        'empty_or_whitespace': raw.apply(lambda col: col.str.strip().eq('').sum()).to_numpy(),
    })
    schema['empty_pct'] = (schema.empty_or_whitespace * 100 / len(raw)).round(4)
    del inferred
    for frame in (raw, scoped):
        frame['_service'] = normalized(frame.service_name)
        frame['_detail'] = normalized(frame.service_name_detail)
    mapping = pd.read_csv(MAPPING, dtype=str, keep_default_na=False)
    validate_mapping(mapping, raw)
    assigned_raw = classify(raw, mapping)
    assigned = classify(scoped, mapping)
    raw_main = counts(assigned_raw, ['main_category'], 'raw').rename(columns={'count': 'raw_count'})
    scoped_main = counts(assigned, ['main_category'], 'explorer').rename(columns={'count': 'explorer_count'})
    main_summary = scoped_main.merge(raw_main, on='main_category', how='outer').fillna(0)
    if main_summary.raw_count.sum() != len(raw) or main_summary.explorer_count.sum() != len(scoped):
        raise ValueError('Main-category totals do not reconcile')
    with SOURCE.open('rb') as stream:
        digest_after = hashlib.file_digest(stream, 'sha256').hexdigest()
    after = SOURCE.stat()
    if digest_before != digest_after or (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
        raise ValueError('Source changed during analysis')

    print('# District 1 Get It Done：第一阶段分类分析\n')
    print(f'来源：{SOURCE.relative_to(HERE.parent)}；SHA-256：`{digest_before}`。')
    print(f'pandas {pd.__version__}；源文件处理前后 SHA-256、大小和 mtime 均一致。')
    print('Explorer 分母：最后一行请求 ID 胜出，然后筛 District 1、2026 年、非空 ID 和有效日期。')
    print('日期沿用来源本地墙上时间；不转换 UTC。不按状态、父请求、坐标或地图视口排除记录。')
    print('API 默认不排除 linked；勾选 exclude_linked 后的口径另列。无坐标仍进入统计但不进入地图。')
    table('1. 数据范围与质量（排除条件可能重叠；不可相加）', pd.DataFrame(stats.items(), columns=['metric', 'value']))
    table('2. 全部字段类型与缺失（标识符建议按文本处理；日期源字段是文本）', schema)
    print(f'\n非空 service_name：全量 {raw._service[raw._service.ne("")].nunique()} 种；'
          f'Explorer {scoped._service[scoped._service.ne("")].nunique()} 种。缺失作为独立一行统计。')
    table('3. 原始类别频数及占比（两列百分比使用各自分母）', display(category_frequency(raw, scoped)))
    profile = raw.groupby('_service').agg(
        raw_count=('_service', 'size'),
        normalized_nonempty_details=('_detail', lambda values: values[values.ne('')].nunique()),
        missing_details=('_detail', lambda values: values.eq('').sum()),
    ).reset_index().rename(columns={'_service': 'service_name'})
    table('4. 每种来源类别的细节丰富程度', display(profile))
    if not args.compact:
        pairs_raw = counts(raw, ['_service', '_detail'], 'raw').rename(columns={'count': 'raw_count'})
        pairs_scoped = counts(scoped, ['_service', '_detail'], 'explorer').rename(columns={'count': 'explorer_count'})
        pairs = pairs_raw.merge(pairs_scoped, on=['_service', '_detail'], how='left').fillna(0)
        pairs['explorer_count'] = pairs.explorer_count.astype(int)
        pairs['raw_within_service_pct'] = (100 * pairs.raw_count / pairs.groupby('_service').raw_count.transform('sum')).round(4)
        table('5. 完整 service_name → service_name_detail 对应（不截断；空值保留）',
              display(pairs.sort_values(['_service', 'raw_count'], ascending=[True, False]).rename(
                  columns={'_service': 'service_name', '_detail': 'service_name_detail'})))
    table('6. 分类映射（条件优先；any 为无条件；fallback 为其余细节）', display(mapping))
    table('7. 大类预计数量及占比', main_summary)
    table('8. Explorer 小类数量及占比', counts(assigned, ['main_category', 'sub_category'], 'explorer'))
    table('9. 排除 linked 后的大类数量（不是默认分母）',
          counts(assigned[normalized(assigned.service_request_parent_id).eq('')], ['main_category'], 'unlinked'))
    unresolved = assigned_raw[assigned_raw.main_category.eq('Needs Review')]
    table('10. 待核查类别及受理类型（不能据此推断问题）',
          display(counts(unresolved, ['_service', 'case_record_type'], 'unresolved')))
    fallback_services = set(mapping.loc[mapping.detail_match.eq('fallback'), 'service_name'])
    explicit = {(rule.service_name, detail) for rule in mapping[mapping.detail_match.eq('in')].itertuples()
                for detail in rule.detail_values.split('|')}
    fallbacks = assigned_raw[assigned_raw._service.isin(fallback_services)].copy()
    fallbacks = fallbacks.loc[[pair not in explicit for pair in zip(fallbacks._service, fallbacks._detail)]]
    table('11. 条件分类的 fallback 明细（供检查已知宽泛值及未来新增细节）',
          display(counts(fallbacks, ['_service', '_detail', 'sub_category'], 'fallback')))
    naming = []
    for field in ('service_name', 'service_name_detail', 'case_record_type'):
        cleaned = normalized(raw[field])
        naming.append((field, raw[field].nunique(), cleaned[cleaned.ne('')].nunique(),
                       int(raw[field].ne(cleaned).sum())))
    table('12. 标签清理影响（原始唯一数含空串；清理后非空）',
          pd.DataFrame(naming, columns=['field', 'raw_unique_including_empty', 'normalized_nonempty_unique', 'whitespace_changed_rows']))
    if not args.compact:
        detail_labels = pd.DataFrame({'detail': raw._detail.drop_duplicates()})
        detail_labels['casefold'] = detail_labels.detail.str.casefold()
        variants = detail_labels[detail_labels.casefold.duplicated(False)]
        table('13. 忽略大小写后相同的细节名称（不自动修改来源）', variants.sort_values(['casefold', 'detail']))
        table('14. service_name × case_record_type 全量对应',
              display(counts(raw, ['_service', 'case_record_type'], 'raw')))
        years = raw.assign(year=raw.date_requested.map(explorer.source_date).map(lambda value: (value or '')[:4]))
        table('15. 历年类别频数（用于识别命名迁移；不是迁移原因的证明）',
              display(counts(years, ['year', '_service'], 'raw').sort_values(['year', 'count'], ascending=[True, False])))
    duplicate_ids = normalized(raw.service_request_id).duplicated(False)
    table('16. 重复请求 ID（只展示结构化字段；不是完整行重复）',
          raw.loc[duplicate_ids, ['service_request_id', 'date_requested', 'service_name', 'service_name_detail']])
    print('''
## 17. 讨论依据与局限

- 7 个主题大类加 Needs Review，共 8 类；来源 Other 和缺失值各自保留，不把已知类别塞入 Other。
- 按报告主题组织而非按受理部门组织。case_record_type 有跨类分布，不能作为问题真值。
- 优先细分漏收、停车、Illegal Dumping、ROW 和 Parks。漏收保留 delayed/potential 的不确定性；
  停车将明确 72 小时和超大车辆细节与同名独立类别对齐；ROW 的标线、标志、设施、积水分别处理。
- 公园采用资产优先：公园涂鸦、垃圾、灯具、排水留在 Parks & Vegetation。这是可讨论的边界；
  全主题涂鸦/垃圾查询应同时查看公园小类，否则会漏计。道路以外不凭描述猜测资产归属。
- 路灯和信号故障、信号配时、交通工程评估分别保留；执法/服务请求不等于已确认违规或损坏。
- Tree Maintenance、Traffic Engineering、Stormwater、街灯及信号细节具有继续细分价值；
  本阶段不将维修工单、部件名和问题类型混成同一层；完整细节表保留下一轮决策依据。
- Parking 与 Parking Violation、Graffiti 与 Graffiti - Public 的年度分布显示命名变化；
  不能只按 service_name 比较趋势。一般 Graffiti 不足以推断公共或私有产权。
- 大小写、前导空格、Community Clean Up/Community Cleanup、SWPP 的 Polution 拼写、
  以及 missing from recent change request 等标签需要讨论；本脚本只做 QHY 式空白清理。
- Other 无细节，缺失 service_name 也无细节；即使有受理类型也不硬猜。
  ESD Collections、AVA、DSD BLUE、Quality of Life Issues、通用 Other/INVESTIGATE 等信息有限，
  保留其来源范围并标明未细分；不会将它们都投入全局 Needs Review。
- 一条请求 ID 的多行版本不同于现实世界重复问题；父请求 linked 单独报告，默认沿用 Explorer 不排除。
  Closed 不证明已经修复；居民报告次数不等于问题数量，也不代表发生率或社区安全。
- 年份不完整、历史标签变化、受理流程、居民使用频率和空间定位质量都会影响比较。
  全量记录虽全部标为 District 1，但未进行边界空间核验；有效坐标不保证实际落在区内。
- 当前方案每条记录恰好命中一个大类和小类；新增来源类别直接报错，新增细节用既定 fallback 并列出。
  本脚本不写源 CSV、现有代码或 SQLite；映射是讨论稿，尚未接入网站。
''')
    print(f'验证通过：{len(raw):,} 条原始记录、{len(scoped):,} 条 Explorer 记录均被完整且唯一分类；'
          f'{len(mapping)} 条规则；{mapping.main_category.nunique()} 个大类；'
          f'{mapping[["main_category", "sub_category"]].drop_duplicates().shape[0]} 个设计小类；无虚构来源标签。')


if __name__ == '__main__':
    main()
