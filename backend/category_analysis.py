"""Audit the approved nine-category mapping without changing source data/cache.

From repository root:
    .venv/bin/python backend/category_analysis.py
    .venv/bin/python -m backend.category_analysis --compact
    .venv/bin/python backend/category_analysis.py --write-report

Only pandas and the standard library are needed. The adjacent mapping CSV is
the editable proposal and is never regenerated by this script. Full output is
Markdown on stdout; --compact omits long detail/case/year tables. No report file
is created unless --write-report is used or the caller redirects stdout.
--write-report writes only docs/category_classification_report.md.

Mapping contract: normalize whitespace exactly like explorer_data.text, then
match service_name exactly (empty means missing). An `in` rule matches one of
the pipe-separated, exact normalized detail_values. It takes priority over the
single `fallback` row for that service. `any` is unconditional and cannot coexist
with conditional rows. Case is preserved; no fuzzy or keyword inference occurs.
classification_method priority: final Needs Review -> needs_review, otherwise
an explicit detail condition -> detail_match, otherwise -> service_default.
This phase audits the fixed 2026-01-01 through 2026-10-26 course snapshot and
fails before classification if it no longer contains exactly 31,667 requests.
Unknown future services fail validation; unknown future details use the explicit
fallback and are printed for review. Each observed detail condition is validated
against the full source, including historical records absent from the Explorer.
"""

