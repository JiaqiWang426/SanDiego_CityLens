def counts(frame, columns, label):
    out = frame.groupby(columns, dropna=False).size().rename('count').reset_index()
    out = out.sort_values(['count', *columns], ascending=[False] + [True] * len(columns))
    out[label + '_pct'] = (out['count'] * 100 / len(frame)).round(4) if len(frame) else 0.0
    return out


def validate_mapping(mapping, raw):
    required = {'service_name', 'main_category', 'sub_category', 'detail_match', 'detail_values', 'notes'}
    if not required.issubset(mapping.columns):
        raise ValueError('Mapping missing columns: ' + str(required - set(mapping.columns)))
    for col in ('service_name', 'main_category', 'sub_category'):
        if not mapping[col].equals(normalized(mapping[col])):
            raise ValueError(f'Mapping has non-normalized whitespace in {col}')
    if (mapping[['main_category', 'sub_category']] == '').any().any():
        raise ValueError('Empty destination category')
    if not mapping.detail_match.isin(['in', 'any', 'fallback']).all():
        raise ValueError('Unsupported detail_match')
    if set(mapping.main_category) != MAIN_CATEGORIES:
        raise ValueError('Mapping must contain exactly the nine approved main categories')
    parking = mapping.sub_category.isin(PARKING_SUBCATEGORIES)
    if not mapping.loc[parking, 'main_category'].eq('Parking & Vehicles').all():
        raise ValueError('All six parking subcategories must map to Parking & Vehicles')
    if set(mapping.loc[mapping.main_category.eq('Parking & Vehicles'), 'sub_category']) != PARKING_SUBCATEGORIES:
        raise ValueError('Parking & Vehicles must contain exactly the approved six subcategories')
    observed, defined = set(raw['_service']), set(mapping.service_name)
    if observed != defined:
        raise ValueError(f'Service coverage mismatch: unmapped={observed-defined}; invented={defined-observed}')
    for service, rules in mapping.groupby('service_name', sort=False):
        defaults = rules[rules.detail_match != 'in']
        conditions = rules[rules.detail_match == 'in']
        if len(defaults) != 1 or (len(conditions) and defaults.iloc[0].detail_match != 'fallback'):
            raise ValueError(f'Exactly one compatible default required for {service!r}')
        if defaults.detail_values.ne('').any():
            raise ValueError('Default rule cannot specify detail_values')
        seen = set()
        actual = set(raw.loc[raw['_service'] == service, '_detail'])
        for rule in conditions.itertuples():
            values = rule.detail_values.split('|')
            if '' in values or any(value != (explorer.text(value) or '') for value in values):
                raise ValueError(f'Invalid detail condition for {service!r}')
            if len(set(values)) != len(values) or seen.intersection(values):
                raise ValueError(f'Overlapping detail rules for {service!r}')
            if not set(values).issubset(actual):
                raise ValueError(f'Invented detail for {service!r}: {set(values)-actual}')
            seen.update(values)


def classify(frame, mapping):
    defaults = mapping[mapping.detail_match != 'in'].set_index('service_name')
    out = frame.copy()
    for destination in ('main_category', 'sub_category'):
        out[destination] = out['_service'].map(defaults[destination])
    out['classification_method'] = 'service_default'
    conditional_matches = pd.Series(0, index=out.index, dtype='int64')
    for rule in mapping[mapping.detail_match == 'in'].itertuples():
        mask = out['_service'].eq(rule.service_name) & out['_detail'].isin(rule.detail_values.split('|'))
        conditional_matches += mask.astype('int64')
        out.loc[mask, ['main_category', 'sub_category']] = [rule.main_category, rule.sub_category]
        out.loc[mask, 'classification_method'] = 'detail_match'
    if conditional_matches.gt(1).any():
        raise ValueError('A record matched multiple conditional rules')
    # Final category has priority over the route used to reach it.
    out.loc[out.main_category.eq('Needs Review'), 'classification_method'] = 'needs_review'
    if out[['main_category', 'sub_category']].isna().any().any():
        raise ValueError('Unmapped record')
    if out[['main_category', 'sub_category']].eq('').any().any():
        raise ValueError('Blank destination category')
    if len(out) != len(frame) or not out.index.equals(frame.index) or not out[frame.columns].equals(frame):
        raise ValueError('Classification changed original rows, fields or order')
    return out


def scope_and_checks(raw):
    """Keep last normalized ID FIRST, then scope, matching cache delete semantics.

    Filtering before deduplication would wrongly retain an earlier in-scope row
    when the final occurrence moved outside District 1 or 2026.
    """
    ids = normalized(raw.service_request_id)
    dates = raw.date_requested.map(explorer.source_date)
    requested_year = dates.map(lambda date: (date or '')[:4])
    valid_id = ids.ne('')
    valid_date = dates.notna()
    district = raw.council_district.str.strip().eq('1')
    year = requested_year.eq('2026')
    last = ~ids.duplicated(keep='last')
    mask = last & valid_id & valid_date & district & year
    # Independently replay QHY's pure normalize() on every row, in source order.
    # This touches neither the existing cache nor any temporary SQLite database.
    replay = {}
    for row in raw[list(explorer.REQUIRED)].to_dict('records'):
        record = explorer.normalize(row)
        key = explorer.text(row['service_request_id'])
        if record is None:
            replay.pop(key, None)
        else:
            replay[key] = record
    scoped = raw.loc[mask].copy()
    if set(normalized(scoped.service_request_id)) != set(replay):
        raise ValueError('Pandas scope differs from QHY normalize replay')
    # Check normalized category and date too, rather than only total count.
    for row in scoped.itertuples():
        record = replay[explorer.text(row.service_request_id)]
        if record[1] != explorer.source_date(row.date_requested) or record[2] != explorer.text(row.service_name):
            raise ValueError('Projection field mismatch')
    stats = {
        'raw_rows': len(raw), 'columns': len(raw.columns),
        'exact_duplicate_rows_excess': int(raw.duplicated().sum()),
        'duplicate_normalized_id_rows_excess': int(ids[valid_id].duplicated().sum()),
        'rows_in_repeated_id_groups': int((ids.duplicated(False) & valid_id).sum()),
        'missing_ids': int((~valid_id).sum()), 'invalid_dates': int((~valid_date).sum()),
        'not_district_1_rows': int((~district).sum()),
        'not_2026_or_invalid_date_rows': int((~year).sum()),
        'last_id_rows': int(last.sum()), 'explorer_rows': len(scoped),
        'explorer_unlocated': sum(row[6] is None for row in replay.values()),
        'explorer_linked': sum(row[10] is not None for row in replay.values()),
        'explorer_first_date': min((row[1] for row in replay.values()), default=''),
        'explorer_last_date': max((row[1] for row in replay.values()), default=''),
        'scope_matches_qhy_normalize_replay': True,
    }
    return scoped, stats


def category_frequency(raw, scoped):
    a = counts(raw, ['_service'], 'raw').rename(columns={'count': 'raw_count'})
    b = counts(scoped, ['_service'], 'explorer').rename(columns={'count': 'explorer_count'})
    out = a.merge(b, how='left', on='_service').fillna(0).rename(columns={'_service': 'service_name'})
    out['explorer_count'] = out.explorer_count.astype(int)
    return out


def missingness(frame, scope):
    fields = ['service_name', 'service_name_detail', 'case_record_type',
              'service_request_id', 'date_requested', 'lat', 'lng']
    rows = []
    for field in fields:
        missing = int(normalized(frame[field]).eq('').sum())
        rows.append((scope, field, len(frame), missing, round(100 * missing / len(frame), 4)))
    return pd.DataFrame(rows, columns=['scope', 'field', 'denominator', 'missing', 'missing_pct'])


def key_and_coordinate_quality(frame, scope):
    ids = normalized(frame.service_request_id)
    dates = frame.date_requested.map(explorer.source_date)
    missing_date = normalized(frame.date_requested).eq('')
    lat, lng = (pd.to_numeric(frame[field], errors='coerce') for field in ('lat', 'lng'))
    missing_coordinates = normalized(frame.lat).eq('') | normalized(frame.lng).eq('')
    valid_coordinates = (lat.map(math.isfinite) & lng.map(math.isfinite)
                         & lat.between(-90, 90) & lng.between(-180, 180))
    metrics = {
        'duplicate_id_rows_excess': int(ids[ids.ne('')].duplicated().sum()),
        'rows_in_repeated_id_groups': int((ids.ne('') & ids.duplicated(False)).sum()),
        'invalid_nonempty_requested_dates': int((dates.isna() & ~missing_date).sum()),
        'duplicate_valid_timestamp_rows_excess': int(dates.dropna().duplicated().sum()),
        'rows_in_repeated_valid_timestamp_groups': int((dates.notna() & dates.duplicated(False)).sum()),
        'exact_duplicate_rows_excess': int(frame[[c for c in frame.columns if not c.startswith('_')]].duplicated().sum()),
        'coordinate_pair_missing_either': int(missing_coordinates.sum()),
        'coordinate_pair_invalid_nonmissing': int((~missing_coordinates & ~valid_coordinates).sum()),
        'coordinate_pair_missing_or_invalid': int((~valid_coordinates).sum()),
        'coordinate_pair_valid': int(valid_coordinates.sum()),
    }
    return pd.DataFrame([(scope, key, value, round(value * 100 / len(frame), 4))
                         for key, value in metrics.items()], columns=['scope', 'metric', 'count', 'pct'])


def all_subcategories(mapping, assigned_raw, assigned):
    keys = ['main_category', 'sub_category']
    out = mapping[keys].drop_duplicates().merge(
        counts(assigned_raw, keys, 'raw').rename(columns={'count': 'raw_count'}), on=keys, how='left')
    out = out.merge(counts(assigned, keys, 'explorer').rename(columns={'count': 'explorer_count'}),
                    on=keys, how='left').fillna(0)
    out[['raw_count', 'explorer_count']] = out[['raw_count', 'explorer_count']].astype(int)
    return out.sort_values(keys)


def rule_quality(mapping, raw, scoped):
    """Audit every rule and distinguish intentional overrides from collisions."""
    defaults = mapping[mapping.detail_match.ne('in')].set_index('service_name')
    rows = []
    candidates = []
    for number, rule in enumerate(mapping.itertuples(), start=2):
        raw_service = raw._service.eq(rule.service_name)
        scoped_service = scoped._service.eq(rule.service_name)
        default = defaults.loc[rule.service_name]
        other_details = set()
        if rule.detail_match != 'in':
            others = mapping[mapping.service_name.eq(rule.service_name) & mapping.detail_match.eq('in')]
            other_details = {detail for item in others.detail_values for detail in item.split('|')}
            raw_mask = raw_service & ~raw._detail.isin(other_details)
            scoped_mask = scoped_service & ~scoped._detail.isin(other_details)
        else:
            details = rule.detail_values.split('|')
            raw_mask = raw_service & raw._detail.isin(details)
            scoped_mask = scoped_service & scoped._detail.isin(details)
        rows.append((number, rule.service_name, rule.detail_match, rule.main_category, rule.sub_category,
                     default.main_category, default.sub_category,
                     bool(rule.detail_match == 'in' and rule.main_category != default.main_category),
                     int(raw_mask.sum()), int(scoped_mask.sum())))
    # Look for observed detail labels that fail exact conditions but differ only
    # in case, spaces or punctuation. Diagnostic only; never apply fuzzy matches.
    def canonical(value):
        return ''.join(character for character in value.casefold() if character.isalnum())

    for service, rules in mapping[mapping.detail_match.eq('in')].groupby('service_name'):
        explicit = {detail for item in rules.detail_values for detail in item.split('|')}
        canonical_details = {}
        for detail in explicit:
            canonical_details.setdefault(canonical(detail), []).append(detail)
        observed = raw.loc[raw._service.eq(service), '_detail'].value_counts()
        for detail, count in observed.items():
            if detail and detail not in explicit and canonical(detail) in canonical_details:
                candidates.append((service, detail, ' / '.join(sorted(canonical_details[canonical(detail)])), int(count)))
    audit = pd.DataFrame(rows, columns=[
        'csv_line', 'service_name', 'rule_type', 'main_category', 'sub_category',
        'default_main', 'default_sub', 'cross_main_override', 'raw_count', 'explorer_count'])
    if audit.raw_count.sum() != len(raw) or audit.explorer_count.sum() != len(scoped):
        raise ValueError('Rule-by-rule counts do not reconcile')
    return audit, pd.DataFrame(candidates, columns=['service_name', 'observed_detail', 'possible_rule_label', 'raw_count'])


def method_counts(assigned_raw, assigned):
    methods = pd.DataFrame({'classification_method': ['detail_match', 'service_default', 'needs_review']})
    for scope, frame in [('raw', assigned_raw), ('explorer', assigned)]:
        counted = counts(frame, ['classification_method'], scope).rename(columns={'count': scope + '_count'})
        methods = methods.merge(counted, on='classification_method', how='left')
    return methods.fillna(0)


def classification_checks(raw, scoped, mapping, assigned_raw, assigned):
    """Validate approved changes against the preceding Phase 2 classification.

    Reconstruct that baseline by moving the six parking subcategories back to
    Traffic & Mobility and park litter back to Parks & Vegetation. The earlier
    park-graffiti approval stays in Graffiti in both versions.
    """
    park_rule = (mapping.service_name.eq('Parks Issue') & mapping.detail_match.eq('in')
                 & mapping.detail_values.eq('Graffiti'))
    if park_rule.sum() != 1 or mapping.loc[park_rule, 'main_category'].iloc[0] != 'Graffiti':
        raise ValueError('Expected exactly one authorized park graffiti rule')
    if mapping.loc[park_rule, 'sub_category'].iloc[0] != 'Park graffiti':
        raise ValueError('Park graffiti subcategory must be preserved')
    litter_rule = (mapping.service_name.eq('Parks Issue') & mapping.detail_match.eq('in')
                   & mapping.detail_values.eq('Trash Can/Overflowing|Trash/Litter'))
    if litter_rule.sum() != 1 or mapping.loc[litter_rule, 'main_category'].iloc[0] != 'Sanitation & Waste':
        raise ValueError('Expected exactly one approved park-litter condition')
    if mapping.loc[litter_rule, 'sub_category'].iloc[0] != 'Park litter and bins':
        raise ValueError('Park litter subcategory must be preserved')
    baseline_mapping = mapping.copy()
    baseline_mapping.loc[mapping.sub_category.isin(PARKING_SUBCATEGORIES), 'main_category'] = 'Traffic & Mobility'
    baseline_mapping.loc[litter_rule, 'main_category'] = 'Parks & Vegetation'
    comparisons = []
    checks = []
    for scope, frame, after in [('raw', raw, assigned_raw), ('explorer', scoped, assigned)]:
        before = classify(frame, baseline_mapping)
        park_graffiti = frame._service.eq('Parks Issue') & frame._detail.eq('Graffiti')
        park_litter = frame._service.eq('Parks Issue') & frame._detail.isin(['Trash Can/Overflowing', 'Trash/Litter'])
        parking = after.sub_category.isin(PARKING_SUBCATEGORIES)
        expected_delta = parking | park_litter
        changed = before[['main_category', 'sub_category']].ne(after[['main_category', 'sub_category']]).any(axis=1)
        no_detail = frame._detail.eq('')
        defaults = mapping[mapping.detail_match.ne('in')].set_index('service_name')
        missing_service = frame._service.eq('')
        source_other = frame._service.eq('Other')
        conditions = {
            'output_row_count_and_order_preserved': len(after) == len(frame) and after.index.equals(frame.index),
            'original_columns_preserved': after[frame.columns].equals(frame),
            'every_record_has_one_main_and_sub': not after[['main_category', 'sub_category']].isna().any().any()
                and not after[['main_category', 'sub_category']].eq('').any().any(),
            'main_counts_sum_to_input': after.groupby('main_category').size().sum() == len(frame),
            'all_nine_main_categories_present': set(after.main_category) == MAIN_CATEGORIES,
            'only_approved_changes_from_phase2': changed.equals(expected_delta),
            'all_subcategory_labels_preserved': before.sub_category.equals(after.sub_category),
            'classification_provenance_preserved': before.classification_method.equals(after.classification_method),
            'parking_subcategories_moved_by_final_issue': after.loc[parking, 'main_category'].eq('Parking & Vehicles').all()
                and after.main_category.eq('Parking & Vehicles').equals(parking),
            'park_graffiti_remains_in_Graffiti': after.loc[park_graffiti, 'main_category'].eq('Graffiti').all()
                and after.loc[park_graffiti, 'sub_category'].eq('Park graffiti').all(),
            'park_litter_in_sanitation': after.loc[park_litter, 'main_category'].eq('Sanitation & Waste').all()
                and after.loc[park_litter, 'sub_category'].eq('Park litter and bins').all(),
            'other_park_issues_unchanged': after.loc[frame._service.eq('Parks Issue') & ~park_litter,
                ['main_category', 'sub_category']].equals(before.loc[frame._service.eq('Parks Issue') & ~park_litter,
                ['main_category', 'sub_category']]),
            'missing_detail_uses_default_main': after.loc[no_detail, 'main_category'].equals(
                frame.loc[no_detail, '_service'].map(defaults.main_category).rename('main_category')),
            'missing_detail_uses_default_sub': after.loc[no_detail, 'sub_category'].equals(
                frame.loc[no_detail, '_service'].map(defaults.sub_category).rename('sub_category')),
            'missing_detail_never_detail_match': after.loc[no_detail, 'classification_method'].ne('detail_match').all(),
            'missing_service_preserved_for_review': after.loc[missing_service, 'main_category'].eq('Needs Review').all()
                and after.loc[missing_service, 'sub_category'].eq('Missing service name').all(),
            'source_other_preserved_for_review': after.loc[source_other, 'main_category'].eq('Needs Review').all()
                and after.loc[source_other, 'sub_category'].eq('Source Other - unresolved').all(),
            'needs_review_method_priority': after.classification_method.eq('needs_review').equals(after.main_category.eq('Needs Review')),
        }
        for check, passed in conditions.items():
            if not passed:
                raise ValueError(f'{scope}: {check} failed')
            checks.append((scope, check, 'PASS'))
        for main_category in sorted(MAIN_CATEGORIES):
            b = int(before.main_category.eq(main_category).sum())
            a = int(after.main_category.eq(main_category).sum())
            comparisons.append((scope, main_category, b, a, a-b))
    return (pd.DataFrame(checks, columns=['scope', 'check', 'result']),
            pd.DataFrame(comparisons, columns=['scope', 'main_category', 'before', 'after', 'delta']))


