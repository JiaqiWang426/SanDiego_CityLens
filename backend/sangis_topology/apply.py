import json
from pathlib import Path

from psycopg.types.json import Jsonb

from backend.verification.intersection_feasibility.study import connection
from .acquire import EvidenceError, digest, now, read, save, sha
from .batch import audit, archived_audit, source_fingerprint, METHOD_VERSION, LocalResolver, stage_a
from .database import maintenance_connection, reference_reader_guard, HERE
from . import stage_c as stage_c_gate
from . import rollout

JOURNAL_SQL = '''CREATE TABLE IF NOT EXISTS citylens_ref.geocode_apply_runs(
 run_id text PRIMARY KEY,approval jsonb NOT NULL,candidate_sha256 text NOT NULL,
 before_audit jsonb NOT NULL,after_audit jsonb,created_at timestamptz NOT NULL DEFAULT now());
 CREATE TABLE IF NOT EXISTS citylens_ref.geocode_apply_history(
 run_id text NOT NULL REFERENCES citylens_ref.geocode_apply_runs(run_id),report_id text NOT NULL,
 outcome text NOT NULL,reason text,old_geocoding jsonb,new_geocoding jsonb,
 recorded_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(run_id,report_id));
 REVOKE ALL ON citylens_ref.geocode_apply_runs,citylens_ref.geocode_apply_history FROM PUBLIC;
 GRANT SELECT ON citylens_ref.geocode_apply_runs,citylens_ref.geocode_apply_history TO citylens_agent_reader;'''


def validate_approval(output, approval_path, stage_c=stage_c_gate.DEFAULT_STAGE_C):
    output = Path(output)
    approval = read(approval_path)
    manifest = read(output/'run-manifest.json')
    for name, checksum in manifest['files'].items():
        if sha(output/name) != checksum:
            raise EvidenceError('Dry run artifact changed: '+name)
    if (approval.get('decision')!='approve_apply' or not approval.get('reviewer') or not approval.get('approved_at')
            or approval.get('candidate_sha256')!=sha(output/'candidates.jsonl')
            or approval.get('run_manifest_sha256')!=sha(output/'run-manifest.json')
            or approval.get('method_version')!=METHOD_VERSION
            or approval.get('snapshot_id')!=manifest['snapshot_id']
            or approval.get('acknowledge_temporal_uncertainty') is not True
            or approval.get('acknowledge_independent_validation_limitations') is not True
            or not approval.get('historical_review_basis')):
        raise EvidenceError('Explicit, matching reviewer approval required')
    independent = read(output/'independent-summary.json')
    if (approval.get('independent_summary_sha256')!=sha(output/'independent-summary.json')
            or not independent.get('complete') or independent.get('systematic_error_discovered')
            or not read(output/'stage-a-replay.json')['passed']
            or not read(output/'rest-archive-comparison.json')['passed']):
        raise EvidenceError('Independent verification or Stage A replay gate failed')
    if set(independent.get('files',{}))!={'independent-plan.json','independent-validation.json','requests.json'}:
        raise EvidenceError('Independent evidence file manifest is incomplete')
    for name,checksum in independent['files'].items():
        path = output/'independent-evidence'/name if name=='requests.json' else output/name
        if sha(path)!=checksum:
            raise EvidenceError('Independent evidence changed after review')
    for entry in read(output/'independent-evidence'/'requests.json')['attempts']:
        if entry['status']=='ok' and sha(output/'independent-evidence'/entry['file'])!=entry['sha256']:
            raise EvidenceError('Independent provider response changed after review')
    requested = approval.get('report_ids')
    if not isinstance(requested,list) or not requested or any(not isinstance(i,str) for i in requested) or len(set(requested))!=len(requested):
        raise EvidenceError('Explicit unique report ID allowlist required')
    proposed = {}
    requested_ids = set(requested)
    with (output/'candidates.jsonl').open(encoding='utf-8') as stream:
        for line in stream:
            c = json.loads(line)
            if c['report_id'] not in requested_ids:
                continue
            # An accepted PAIR can also contain definitively rejected nodes.
            # Keep their evidence in the file, but never treat it as the pin.
            if c['classification']=='accepted_candidate' and c['distinct_valid_candidate_nodes']==1 and c['topology_outcome']!='supported':
                continue
            if (c['report_id'] in proposed or c['classification']!='accepted_candidate'
                    or c['topology_outcome']!='supported' or c['distinct_valid_candidate_nodes']!=1
                    or c['precision']!='intersection_approximate' or c['snapshot_id']!=manifest['snapshot_id']
                    or c['method_version']!=METHOD_VERSION or c['srid']!=4326
                    or not isinstance(c['longitude'],(int,float)) or not isinstance(c['latitude'],(int,float))
                    or not (-117.6<=c['longitude']<=-116.8 and 32.5<=c['latitude']<=33.2)):
                raise EvidenceError('Allowlist contains an ineligible candidate')
            proposed[c['report_id']] = c
    if set(proposed)!=set(requested):
        raise EvidenceError('Allowlist contains missing report IDs')
    # Recompute topology from the immutable local reference, rather than trusting
    # an editable candidate file as the sole source of deployable coordinates.
    # Stage B evaluated each pair in canonical sorted order (pair_key); primary/cross
    # segment IDs are only comparable in that same orientation.
    pairs = {stage_a.pair_key(c['normalized_primary_road'],c['normalized_cross_road']) for c in proposed.values()}
    with connection() as conn:
        reference_reader_guard(conn)
        resolver = LocalResolver(conn,manifest['snapshot_id'],pairs)
    for c in proposed.values():
        r = resolver.resolve(*stage_a.pair_key(c['normalized_primary_road'],c['normalized_cross_road']))
        supported = [n for n in r['candidates'] if n['status']=='supported']
        if r['status']!='accepted_candidate' or len(supported)!=1:
            raise EvidenceError('Local topology no longer supports an approved proposal')
        n = supported[0]
        if (n['node_id']!=c['node_id'] or abs(n['longitude']-c['longitude'])>1e-10
                or abs(n['latitude']-c['latitude'])>1e-10
                or n['primary_segment_ids']!=c['primary_segment_ids'] or n['cross_segment_ids']!=c['cross_segment_ids']):
            raise EvidenceError('Candidate differs from local topology replay')
    # Stage C: every approved report must be an identical, strictly validated
    # allowlist entry bound by artifact hashes. There is no bypass.
    gate = stage_c_gate.validate_stage_c(stage_c,approval,proposed)
    return approval,proposed,gate


def eligibility(current,candidate):
    if not current:
        return 'missing_record'
    if current['geocode_status']!='pending' or current['has_location']:
        return 'not_pending_or_already_located'
    if source_fingerprint(current)!=candidate['source_address_fingerprint']:
        return 'stale_source_address'
    return None


def nonselected_digest(conn,ids):
    return conn.execute("SELECT md5(string_agg(md5(to_jsonb(c)::text),'' ORDER BY report_id)) AS digest FROM citylens.traffic_collisions c WHERE NOT(report_id=ANY(%s))",(ids,)).fetchone()['digest']


def rollout_baseline_check(conn,gate,baseline):
    """Staged rollout: the database may differ from the Stage C before-state
    ONLY by guarded updates already journaled for allowlisted reports."""
    before = gate['before_state']
    allow_ids = sorted(gate['allowlist'])
    expected = before['collision_audit']
    if baseline['records']!=expected['records'] or baseline['source_fields']!=expected['source_fields']:
        raise EvidenceError('Collision records or original fields changed since Stage C validation')
    if nonselected_digest(conn,allow_ids)!=before['non_allowlist_rows']:
        raise EvidenceError('A collision outside the Stage C allowlist changed since validation')
    applied = conn.execute("SELECT count(DISTINCT report_id) AS n FROM citylens_ref.geocode_apply_history WHERE outcome='updated' AND report_id=ANY(%s)",(allow_ids,)).fetchone()['n']
    statuses = dict(expected['statuses'])
    statuses['pending'] = statuses.get('pending',0)-applied
    statuses['matched'] = statuses.get('matched',0)+applied
    if baseline['statuses']!={k:v for k,v in statuses.items() if v} or baseline['located']!=expected['located']+applied:
        raise EvidenceError('Global baseline is not explained by journaled Stage C rollout batches')
    return applied


def deploy(output,approval_path,*,apply=False,batch_size=100,stage_c=stage_c_gate.DEFAULT_STAGE_C,baseline_snapshot=None,baseline_sha256=None):
    """Stage C intersection deployment. With `baseline_snapshot` (the final
    milestone's per-row rollout baseline) other guarded allowlists may have
    been applied first; without it the original Stage C aggregate check holds."""
    if not 1<=batch_size<=200:
        raise EvidenceError('Transaction batch size must be 1..200')
    approval,proposed,gate = validate_approval(output,approval_path,stage_c)
    snapshot = None
    if baseline_snapshot is not None:
        snapshot = rollout.load_snapshot(baseline_snapshot,baseline_sha256)
        if snapshot['collision_audit']!=gate['before_state']['collision_audit']:
            raise EvidenceError('Rollout baseline was not captured from the Stage C validated state')
    run_id = digest({'candidate':approval['candidate_sha256'],'approval':sha(approval_path)})
    if not apply:
        with connection() as conn:
            rows = conn.execute('SELECT *,location IS NOT NULL AS has_location FROM citylens.traffic_collisions WHERE report_id=ANY(%s)',(list(proposed),)).fetchall()
        current = {r['report_id']:r for r in rows}
        counts = Counter(eligibility(current.get(i),c) or 'eligible' for i,c in proposed.items())
        result = {'run_id':run_id,'mode':'deployment_preflight','collision_updates':0,'counts':dict(counts),
                  'approved_reports':len(proposed),'stage_c_allowlist_reports':len(gate['allowlist']),
                  'stage_c_validation_manifest_sha256':gate['manifest_sha256']}
        save(Path(stage_c)/'deployment-preflight.json',result)
        return result
    with maintenance_connection(apply=True) as conn:
        conn.execute('SELECT pg_advisory_lock(8420163)')
        conn.execute(JOURNAL_SQL)
        prior = conn.execute('SELECT * FROM citylens_ref.geocode_apply_runs WHERE run_id=%s',(run_id,)).fetchone()
        baseline = prior['before_audit'] if prior else audit(conn)
        if not prior:
            if snapshot is not None:
                baseline['rollout_baseline'] = rollout.check(conn,snapshot,baseline)
            else:
                baseline['stage_c_previously_applied'] = rollout_baseline_check(conn,gate,baseline)
            baseline['archived_sources'] = archived_audit(conn)
            baseline['nonselected_rows'] = nonselected_digest(conn,list(proposed))
        conn.execute('INSERT INTO citylens_ref.geocode_apply_runs(run_id,approval,candidate_sha256,before_audit) VALUES(%s,%s,%s,%s) ON CONFLICT DO NOTHING',
                     (run_id,Jsonb(approval),approval['candidate_sha256'],Jsonb(baseline)))
        checks = conn.execute("SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint WHERE conrelid='citylens.traffic_collisions'::regclass AND conname='traffic_collisions_geocode_precision_check'").fetchone()
        if not checks or 'intersection_approximate' not in checks['definition']:
            if approval.get('allow_precision_migration') is not True:
                raise EvidenceError('Reviewer must explicitly approve the precision constraint migration')
            conn.execute((HERE/'deploy.sql').read_text(encoding='utf-8'))
        conn.commit()
        ids = sorted(proposed)
        invocation_counts = Counter()
        for start in range(0,len(ids),batch_size):
            with conn.transaction():
                for report_id in ids[start:start+batch_size]:
                    if conn.execute('SELECT 1 FROM citylens_ref.geocode_apply_history WHERE run_id=%s AND report_id=%s',(run_id,report_id)).fetchone():
                        invocation_counts['skipped'] += 1
                        continue  # Durable committed checkpoint; never duplicate.
                    c = proposed[report_id]
                    current = conn.execute('SELECT *,location IS NOT NULL AS has_location FROM citylens.traffic_collisions WHERE report_id=%s FOR UPDATE',(report_id,)).fetchone()
                    reason = eligibility(current,c)
                    old = {k:current[k] for k in ('geocode_status','geocode_provider','geocode_precision','geocoded_at','geocode_details')} if current else None
                    if old:
                        old['geocoded_at'] = old['geocoded_at'].isoformat() if old['geocoded_at'] else None
                        old['location'] = current['location']
                    if reason:
                        outcome,new = 'rejected',None
                    else:
                        allowed = gate['allowlist'][report_id]
                        evidence = {'prior_geocoding':old,'stage_b':c,'approval':{'run_id':run_id,'reviewer':approval['reviewer'],'approved_at':approval['approved_at']},
                                    'stage_c':{**{k:allowed[k] for k in ('validation_version','validation_status','topology_status','independent_status',
                                                'provenance_status','acceptance_reasons','independent_evidence_sha256','topology_evidence_sha256','validated_at')},
                                               'validation_manifest_sha256':gate['manifest_sha256'],'allowlist_sha256':approval['stage_c_allowlist_sha256']},
                                    'validation_method':METHOD_VERSION,'historical_position_verified':False,
                                    'precision_note':'intersection_approximate: present-day reference junction, not an exact or collision-date position'}
                        changed = conn.execute('''UPDATE citylens.traffic_collisions SET
                            location=ST_SetSRID(ST_MakePoint(%s,%s),4326)::geography,
                            geocode_status='matched',geocode_provider='SanGIS local topology',geocode_precision='intersection_approximate',
                            geocoded_at=now(),geocode_details=%s WHERE report_id=%s AND geocode_status='pending' AND location IS NULL
                            RETURNING geocode_status,geocode_precision,ST_IsValid(location::geometry) AS valid''',
                            (c['longitude'],c['latitude'],Jsonb(evidence),report_id)).fetchone()
                        if not changed or not changed['valid']:
                            raise EvidenceError('Guarded update failed')
                        outcome,new = 'updated',evidence
                    conn.execute('INSERT INTO citylens_ref.geocode_apply_history(run_id,report_id,outcome,reason,old_geocoding,new_geocoding) VALUES(%s,%s,%s,%s,%s,%s)',
                                 (run_id,report_id,outcome,reason,Jsonb(old),Jsonb(new)))
                    invocation_counts[outcome] += 1
                # Invariants are checked BEFORE committing each bounded batch.
                after = audit(conn)
                if after['records']!=baseline['records'] or after['source_fields']!=baseline['source_fields'] or archived_audit(conn)!=baseline['archived_sources']:
                    raise EvidenceError('Source/count preservation invariant failed; current batch rolled back')
                # Restrict the matched baseline to rows outside this run's allowlist.
                old_matched = conn.execute('''SELECT md5(string_agg(md5(to_jsonb(c)::text),'' ORDER BY report_id)) AS digest
                    FROM citylens.traffic_collisions c WHERE geocode_status='matched' AND NOT(report_id=ANY(%s))''',(ids,)).fetchone()['digest']
                if old_matched!=baseline['matched_rows']:
                    raise EvidenceError('Existing matched rows changed; current batch rolled back')
                if nonselected_digest(conn,ids)!=baseline['nonselected_rows']:
                    raise EvidenceError('Nonselected collision changed; current batch rolled back')
                updated = conn.execute("SELECT count(*) AS n FROM citylens_ref.geocode_apply_history WHERE run_id=%s AND outcome='updated'",(run_id,)).fetchone()['n']
                expected_statuses = dict(baseline['statuses'])
                expected_statuses['pending'] = expected_statuses.get('pending',0)-updated
                expected_statuses['matched'] = expected_statuses.get('matched',0)+updated
                expected_statuses = {k:v for k,v in expected_statuses.items() if v}
                if after['statuses']!=expected_statuses or after['located']!=baseline['located']+updated:
                    raise EvidenceError('Geocoding count reconciliation failed')
                invalid = conn.execute('''SELECT count(*) AS n FROM citylens.traffic_collisions c
                   JOIN citylens_ref.geocode_apply_history h ON h.report_id=c.report_id AND h.run_id=%s AND h.outcome='updated'
                   WHERE c.location IS NULL OR NOT ST_IsValid(c.location::geometry)
                    OR c.geocode_precision IS DISTINCT FROM 'intersection_approximate'
                    OR c.geocode_provider IS DISTINCT FROM 'SanGIS local topology'
                    OR c.geocode_details->'stage_b'->>'snapshot_id' IS DISTINCT FROM %s
                    OR c.geocode_details->'stage_c'->>'validation_status' IS DISTINCT FROM 'pass' ''',(run_id,approval['snapshot_id'])).fetchone()['n']
                if invalid:
                    raise EvidenceError('Applied spatial/provenance verification failed')
                conn.execute('UPDATE citylens_ref.geocode_apply_runs SET after_audit=%s WHERE run_id=%s',(Jsonb(after),run_id))
        counts = {r['outcome']:r['n'] for r in conn.execute('SELECT outcome,count(*) AS n FROM citylens_ref.geocode_apply_history WHERE run_id=%s GROUP BY 1',(run_id,))}
        conn.commit()
    with connection() as conn:
        guard = reference_reader_guard(conn)
    result = {'run_id':run_id,'mode':'apply','counts':{'inserted':0,'updated':counts.get('updated',0),'rejected':counts.get('rejected',0),'skipped':invocation_counts['skipped']},
              'invocation_counts':dict(invocation_counts),
              'before':baseline,'after':after,'agent_reference_permissions':guard,'finished_at':now()}
    save(Path(output)/'apply-result.json',result)
    return result


# ------------------------------------------------------------------ final milestone
# Status-specific extension for the final historical allowlist. It shares the
# journal tables, advisory lock and per-row rollout baseline with Stage C, but has
# its own approval binding. Stage C's Pending-only eligibility is unchanged: here
# each row must still hold EXACTLY the original status recorded in the allowlist,
# that status must be explicitly approved, and the coordinate must still be NULL.

FINAL_STATUSES = {'no_match','ambiguous','pending'}
FINAL_PROVIDERS = {'block_approximate':'SanGIS road centerline','intersection_approximate':'SanGIS local topology'}


def read_final_allowlist(path):
    import csv
    rows = {}
    with Path(path).open(encoding='utf-8',newline='') as stream:
        for row in csv.DictReader(stream):
            row['segment_ids'] = json.loads(row['segment_ids']) if row['segment_ids'] else []
            row['name_sources'] = json.loads(row['name_sources']) if row['name_sources'] else []
            row['longitude'],row['latitude'] = float(row['longitude']),float(row['latitude'])
            row['node_id'] = int(row['node_id']) if row['node_id'] else None
            row['block'] = int(row['block']) if row['block'] else None
            if row['report_id'] in rows:
                raise EvidenceError('Duplicate report in final allowlist')
            rows[row['report_id']] = row
    return rows


def replay_final_entries(entries,snapshot_id):
    """Recompute every approved coordinate from the immutable local reference."""
    from . import roadblock
    from .final_geocoding import ROADBLOCK_PROVIDER
    blocks,intersections,resolver = {},{},None
    with connection() as conn:
        reference_reader_guard(conn)
        index = roadblock.load_index(conn,snapshot_id)
        for e in entries.values():
            if e['provider']==ROADBLOCK_PROVIDER:
                key = (e['street'],e['block'])
                if key not in blocks:
                    blocks[key] = roadblock.resolve_block(conn,snapshot_id,index,*key)
            else:
                intersections[e['report_id']] = tuple(e['street'].split(' / '))
        if intersections:
            resolver = LocalResolver(conn,snapshot_id,sorted(set(intersections.values())))
    for e in entries.values():
        if e['provider']==ROADBLOCK_PROVIDER:
            r = blocks[(e['street'],e['block'])]
            ok = (r['status']=='accepted_candidate' and r['segment_ids']==e['segment_ids']
                  and abs(r['longitude']-e['longitude'])<=1e-10 and abs(r['latitude']-e['latitude'])<=1e-10)
        else:
            r = resolver.resolve(*intersections[e['report_id']])
            nodes = [n for n in r['candidates'] if n['status']=='supported']
            ok = (r['status']=='accepted_candidate' and len(nodes)==1 and nodes[0]['node_id']==e['node_id']
                  and abs(nodes[0]['longitude']-e['longitude'])<=1e-10 and abs(nodes[0]['latitude']-e['latitude'])<=1e-10)
        if not ok:
            raise EvidenceError('Approved final coordinate differs from local reference replay: '+e['report_id'])


def validate_final_approval(final_dir,approval_path):
    from . import final_geocoding
    final_dir = Path(final_dir)
    approval = read(approval_path)
    manifest = read(final_dir/'validation-manifest.json')
    for name,checksum in manifest['files'].items():
        if sha(final_dir/name)!=checksum:
            raise EvidenceError('Final geocoding artifact changed after validation: '+name)
    summary = read(final_dir/'summary.json')
    statuses = approval.get('allowed_original_statuses')
    if (approval.get('decision')!='approve_apply' or not approval.get('reviewer') or not approval.get('approved_at')
            or approval.get('method_version')!=final_geocoding.METHOD_VERSION
            or approval.get('final_validation_manifest_sha256')!=sha(final_dir/'validation-manifest.json')
            or approval.get('final_allowlist_sha256')!=sha(final_dir/'deployment_allowlist.csv')
            or approval.get('snapshot_id')!=summary['snapshot_id']
            or approval.get('acknowledge_temporal_uncertainty') is not True
            or approval.get('acknowledge_independent_validation_limitations') is not True
            or approval.get('acknowledge_approximate_precision') is not True
            or not approval.get('historical_review_basis')
            or not isinstance(statuses,list) or not statuses or not set(statuses)<=FINAL_STATUSES):
        raise EvidenceError('Explicit, matching final-allowlist approval required')
    if not summary['deployment_gate']['allowlist_ready_for_review'] or summary['quality']['systematic_issue_detected'] is not False:
        raise EvidenceError('Final quality gate is not satisfied')
    requested = approval.get('report_ids')
    if not isinstance(requested,list) or not requested or any(not isinstance(i,str) for i in requested) or len(set(requested))!=len(requested):
        raise EvidenceError('Explicit unique report ID allowlist required')
    allow = read_final_allowlist(final_dir/'deployment_allowlist.csv')
    entries = {}
    for report_id in requested:
        e = allow.get(report_id)
        if (e is None or e['validation_status']!='pass' or e['original_status'] not in statuses
                or FINAL_PROVIDERS.get(e['precision'])!=e['provider'] or e['snapshot_id']!=summary['snapshot_id']
                or not (-117.6<=e['longitude']<=-116.8 and 32.5<=e['latitude']<=33.2)):
            raise EvidenceError('Approved report is not an eligible final allowlist entry for the approved statuses')
        entries[report_id] = e
    replay_final_entries(entries,summary['snapshot_id'])
    snapshot = rollout.load_snapshot(final_dir/'before-row-digests.json.gz',manifest['files']['before-row-digests.json.gz'])
    return approval,entries,snapshot


def final_eligibility(current,entry):
    if not current:
        return 'missing_record'
    if current['geocode_status']!=entry['original_status'] or current['has_location']:
        return 'status_changed_or_already_located'
    if source_fingerprint(current)!=entry['source_address_fingerprint']:
        return 'stale_source_address'
    return None


FINAL_PROVENANCE_SQL = """SELECT count(*) AS n FROM citylens.traffic_collisions c
   JOIN citylens_ref.geocode_apply_history h ON h.report_id=c.report_id AND h.run_id=%s AND h.outcome='updated'
   WHERE c.location IS NULL OR NOT ST_IsValid(c.location::geometry) OR c.geocode_status<>'matched'
    OR c.geocode_precision IS DISTINCT FROM c.geocode_details->'final_geocoding'->>'precision'
    OR c.geocode_provider IS DISTINCT FROM c.geocode_details->'final_geocoding'->>'provider'
    OR c.geocode_details->'final_geocoding'->>'validation_status' IS DISTINCT FROM 'pass'"""

FINAL_UPDATE_SQL = """UPDATE citylens.traffic_collisions SET
    location=ST_SetSRID(ST_MakePoint(%s,%s),4326)::geography,geocode_status='matched',geocode_provider=%s,
    geocode_precision=%s,geocoded_at=now(),geocode_details=%s
    WHERE report_id=%s AND geocode_status=%s AND location IS NULL
    RETURNING ST_IsValid(location::geometry) AS valid"""


def deploy_final(final_dir,approval_path,*,apply=False,batch_size=100):
    if not 1<=batch_size<=200:
        raise EvidenceError('Transaction batch size must be 1..200')
    final_dir = Path(final_dir)
    approval,entries,snapshot = validate_final_approval(final_dir,approval_path)
    run_id = digest({'final_allowlist':approval['final_allowlist_sha256'],'approval':sha(approval_path)})
    ids = sorted(entries)
    if not apply:
        with connection() as conn:
            rows = {r['report_id']:r for r in conn.execute('SELECT *,location IS NOT NULL AS has_location FROM citylens.traffic_collisions WHERE report_id=ANY(%s)',(ids,))}
            drift = rollout.check(conn,snapshot,audit(conn))
        counts = Counter(final_eligibility(rows.get(i),e) or 'eligible' for i,e in entries.items())
        result = {'run_id':run_id,'mode':'final_deployment_preflight','collision_updates':0,'counts':dict(counts),
                  'approved_reports':len(ids),'by_original_status':dict(Counter(e['original_status'] for e in entries.values())),
                  'rollout_baseline':drift}
        save(final_dir/'deployment-preflight.json',result)
        return result
    with maintenance_connection(apply=True) as conn:
        conn.execute('SELECT pg_advisory_lock(8420163)')  # Same lock as Stage C: one writer at a time.
        conn.execute(JOURNAL_SQL)
        prior = conn.execute('SELECT * FROM citylens_ref.geocode_apply_runs WHERE run_id=%s',(run_id,)).fetchone()
        baseline = prior['before_audit'] if prior else audit(conn)
        if not prior:
            baseline['rollout_baseline'] = rollout.check(conn,snapshot,baseline)
            baseline['archived_sources'] = archived_audit(conn)
        conn.execute('INSERT INTO citylens_ref.geocode_apply_runs(run_id,approval,candidate_sha256,before_audit) VALUES(%s,%s,%s,%s) ON CONFLICT DO NOTHING',
                     (run_id,Jsonb(approval),approval['final_allowlist_sha256'],Jsonb(baseline)))
        if any(e['precision']=='intersection_approximate' for e in entries.values()):
            check = conn.execute("SELECT pg_get_constraintdef(oid) AS definition FROM pg_constraint WHERE conrelid='citylens.traffic_collisions'::regclass AND conname='traffic_collisions_geocode_precision_check'").fetchone()
            if not check or 'intersection_approximate' not in check['definition']:
                if approval.get('allow_precision_migration') is not True:
                    raise EvidenceError('Reviewer must explicitly approve the precision constraint migration')
                conn.execute((HERE/'deploy.sql').read_text(encoding='utf-8'))
        conn.commit()
        invocation_counts = Counter()
        after = baseline
        for start in range(0,len(ids),batch_size):
            with conn.transaction():
                for report_id in ids[start:start+batch_size]:
                    if conn.execute('SELECT 1 FROM citylens_ref.geocode_apply_history WHERE run_id=%s AND report_id=%s',(run_id,report_id)).fetchone():
                        invocation_counts['skipped'] += 1
                        continue
                    e = entries[report_id]
                    current = conn.execute('SELECT *,location IS NOT NULL AS has_location FROM citylens.traffic_collisions WHERE report_id=%s FOR UPDATE',(report_id,)).fetchone()
                    reason = final_eligibility(current,e)
                    old = {k:current[k] for k in ('geocode_status','geocode_provider','geocode_precision','geocoded_at','geocode_details')} if current else None
                    if old:
                        old['geocoded_at'] = old['geocoded_at'].isoformat() if old['geocoded_at'] else None
                        old['location'] = current['location']
                    if reason:
                        outcome,new = 'rejected',None
                    else:
                        evidence = {'prior_geocoding':old,'final_geocoding':dict(e),
                                    'approval':{'run_id':run_id,'reviewer':approval['reviewer'],'approved_at':approval['approved_at']},
                                    'validation_method':e['method_version'],'historical_position_verified':False,
                                    'precision_note':e['precision']+': present-day SanGIS reference geometry, not an exact or collision-date position'}
                        changed = conn.execute(FINAL_UPDATE_SQL,(e['longitude'],e['latitude'],e['provider'],e['precision'],Jsonb(evidence),
                                                                 report_id,e['original_status'])).fetchone()
                        if not changed or not changed['valid']:
                            raise EvidenceError('Guarded final update failed')
                        outcome,new = 'updated',evidence
                    conn.execute('INSERT INTO citylens_ref.geocode_apply_history(run_id,report_id,outcome,reason,old_geocoding,new_geocoding) VALUES(%s,%s,%s,%s,%s,%s)',
                                 (run_id,report_id,outcome,reason,Jsonb(old),Jsonb(new)))
                    invocation_counts[outcome] += 1
                after = audit(conn)
                if archived_audit(conn)!=baseline['archived_sources']:
                    raise EvidenceError('Archived source rows changed; current batch rolled back')
                rollout.check(conn,snapshot,after)  # Counts, original fields, drift and journal reconcile.
                if conn.execute(FINAL_PROVENANCE_SQL,(run_id,)).fetchone()['n']:
                    raise EvidenceError('Applied spatial/provenance verification failed; current batch rolled back')
                conn.execute('UPDATE citylens_ref.geocode_apply_runs SET after_audit=%s WHERE run_id=%s',(Jsonb(after),run_id))
        counts = {r['outcome']:r['n'] for r in conn.execute('SELECT outcome,count(*) AS n FROM citylens_ref.geocode_apply_history WHERE run_id=%s GROUP BY 1',(run_id,))}
        conn.commit()
    with connection() as conn:
        guard = reference_reader_guard(conn)
    result = {'run_id':run_id,'mode':'final_apply','counts':{'updated':counts.get('updated',0),'rejected':counts.get('rejected',0),
              'skipped':invocation_counts['skipped']},'invocation_counts':dict(invocation_counts),
              'before':baseline,'after':after,'agent_reference_permissions':guard,'finished_at':now()}
    save(final_dir/'apply-result.json',result)
    return result
